// tests/schema-audit-load-agreement-oracle.test.mjs — BLZ-407.
//
// THE PRODUCT ASSERTION: `blaze audit`'s `ok` and the load path's refusal agree, for every
// schema-override shape. Before this ticket they did not — a board whose `blaze.config.json`
// carried `{"schema": {"types": {"spike": 7}}}` made `blaze audit` report `ok=true` while
// every non-exempt verb refused with `SchemaOverrideError`, the SAME message, because
// `auditCorpus` read `validateSchema`'s flattened strings and filed every problem under one
// soft kind — the severity tag `collectSchemaProblems` already carries was thrown away.
//
// GROUND TRUTH IS `assertSchemaValid`, NOT THE AUDIT. Every case below runs the real load-path
// mechanism (mirroring `scripts/cli.mjs`'s preflight exactly: the top layer, then each project
// layer, refuse if either throws) and compares its actual throw/no-throw against `auditCorpus`'s
// actual `ok`. Neither side is derived from the other, and neither is computed from a hardcoded
// list of "these shapes are hard" — that is the vacuity trap a run of five wrong severities in a
// row on a sibling ticket fell into, each round pinning only the case that made its round's
// claim true.
//
// THE CROSS-PRODUCT is generated by nested loops over ONE list of override shapes, applied to
// BOTH layers (`blaze.config.json`'s `schema` and a `project.json`'s `schema`) — not a
// hand-written table of (config, project) pairs. The shape list itself is read off
// `collectSchemaProblems` (scripts/model/schema-config.mjs): one entry per `hard(...)` call
// site, one per `soft(...)` call site, and the well-formed controls.
import { test, describe } from "node:test";
import assert from "node:assert/strict";
import { auditCorpus } from "../scripts/model/audit.mjs";
import { resolveSchema, assertSchemaValid, validateSchema, collectSchemaProblems }
  from "../scripts/model/schema-config.mjs";

// --- the override shapes, one per branch of collectSchemaProblems ----------------------------
// Each entry is `[name, value]`, where `value` is what would sit at `schema` in either
// blaze.config.json or project.json. `undefined` means the block is absent — a layer's own
// well-formed control. A shape is applied identically at either layer; which branch it
// exercises where is NOT hand-predicted here (some are layer-specific, e.g. a per-project
// `linkTypes` block is inert only at the project layer) — the oracle asks the real functions,
// not this list, what a given placement produces.

// One custom type ("spike") and one custom workflow ("tiny") isolate every shape from the
