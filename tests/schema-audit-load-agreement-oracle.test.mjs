const SHAPES = [...HARD_SHAPES, ...SOFT_SHAPES, ...CONTROL_SHAPES];

// --- ground truth and the mechanism under test ------------------------------------------------

const buildConfig = (v) => (v === undefined ? {} : { schema: v });
const buildProject = (v) => (v === undefined ? { key: "P" } : { key: "P", schema: v });

/** Mirrors scripts/cli.mjs's preflight EXACTLY: the top layer, then each project layer, and
 *  refuse the moment either throws. This — NOT a prediction — is ground truth. */
function loadPathRefuses(config, project) {
  const top = resolveSchema({ config });
  try { assertSchemaValid({ ...top, config }); }
  catch { return true; }
  const resolved = { ...resolveSchema({ config, project }), linkTypes: top.linkTypes };
  try { assertSchemaValid({ ...resolved, config, project }); }
  catch { return true; }
  return false;
}

/** What `auditCorpus` SHOULD produce for the schema layer, computed independently of it: the
 *  same top-then-project walk with cross-layer dedup by message, but built here from
 *  `collectSchemaProblems` directly rather than by calling `auditCorpus` and trusting its own
 *  bookkeeping. Returns the hard/soft partition of every DISTINCT message. */
function expectedPartition(config, project) {
  const topResolved = resolveSchema({ config });
  const endpointTypes = { ...topResolved.types, ...resolveSchema({ config, project }).types };
  const topProblems = collectSchemaProblems({ ...topResolved, config, endpointTypes });
  const topByMsg = new Map();
  for (const p of topProblems) if (!topByMsg.has(p.message)) topByMsg.set(p.message, p.hard);
  const resolved = { ...resolveSchema({ config, project }), linkTypes: topResolved.linkTypes };
  const projProblems = collectSchemaProblems({ ...resolved, config, project, endpointTypes })
    .filter((p) => !topByMsg.has(p.message));
  const hard = new Set(), soft = new Set();
  for (const [msg, isHard] of topByMsg) (isHard ? hard : soft).add(msg);
  for (const p of projProblems) (p.hard ? hard : soft).add(p.message);
  return { hard, soft };
}

/** The union `validateSchema` itself would report for the same two layers, deduped the same
 *  way — the independent reference for "no problem lost or duplicated" (validateSchema is the
 *  long-established, separately-tested reporting path; this does not call collectSchemaProblems
 *  at all). */
function expectedDetailSetViaValidateSchema(config, project) {
  const topResolved = resolveSchema({ config });
  const endpointTypes = { ...topResolved.types, ...resolveSchema({ config, project }).types };
  const topMsgs = validateSchema({ ...topResolved, config, endpointTypes });
  const topSet = new Set(topMsgs);
  const resolved = { ...resolveSchema({ config, project }), linkTypes: topResolved.linkTypes };
  const projMsgs = validateSchema({ ...resolved, config, project, endpointTypes })
    .filter((m) => !topSet.has(m));
  return new Set([...topSet, ...projMsgs]);
}

const oneGoalTicket = { frontmatter: { id: "P-1", type: "goal", components: [], labels: [], links: [] }, body: "x" };

const sorted = (s) => [...s].sort();

describe("BLZ-407 oracle: blaze audit's ok agrees with the load path's refusal, for every schema-override shape", () => {
  let cases = 0;
  let clauses = 0;
  const check = (cond, msg) => { clauses++; assert.ok(cond, msg); };
  const sameSet = (actual, expected, msg) => { clauses++; assert.deepEqual(sorted(actual), sorted(expected), msg); };

  for (const [configName, configValue] of SHAPES) {
    for (const [projectName, projectValue] of SHAPES) {
      cases++;
      test(`config=[${configName}] x project=[${projectName}]`, () => {
        const config = buildConfig(configValue);
        const project = buildProject(projectValue);

        const refused = loadPathRefuses(config, project);
        const audit = auditCorpus({ tickets: [oneGoalTicket], projects: { P: project }, config });

        // --- the ok/refusal agreement, both directions ----------------------------------
        check(!(refused && audit.ok),
          `assertSchemaValid throws for config=[${configName}] project=[${projectName}] `
          + `but audit.ok is still true`);
        check(!(!refused && !audit.ok),
          `assertSchemaValid does not throw for config=[${configName}] project=[${projectName}] `
          + `but audit.ok is false — the mirror-image over-refusal`);

        // --- the finding-level claim: no problem lost, duplicated, or under the wrong kind ---
        const actualHard = new Set(audit.findings
          .filter((f) => f.kind === "schema-malformed").map((f) => f.detail));
        const actualSoft = new Set(audit.findings
          .filter((f) => f.kind === "schema-invalid").map((f) => f.detail));
        const expected = expectedPartition(config, project);
        sameSet(actualHard, expected.hard,
          `schema-malformed details differ from collectSchemaProblems's hard partition `
          + `for config=[${configName}] project=[${projectName}]`);
        sameSet(actualSoft, expected.soft,
          `schema-invalid details differ from collectSchemaProblems's soft partition `
          + `for config=[${configName}] project=[${projectName}]`);
        check([...actualHard].every((m) => !actualSoft.has(m)),
          `a message is filed under BOTH schema-malformed and schema-invalid for `
          + `config=[${configName}] project=[${projectName}]`);

        // --- the union equals validateSchema's own output, as a set (independent reference) ---
        const union = new Set([...actualHard, ...actualSoft]);
        sameSet(union, expectedDetailSetViaValidateSchema(config, project),
          `schema-malformed ∪ schema-invalid details differ from validateSchema's output `
          + `for config=[${configName}] project=[${projectName}]`);
      });
    }
  }

  test("the oracle's own scale — reported so it cannot silently shrink", () => {
    const expectedCases = SHAPES.length * SHAPES.length;
    assert.equal(cases, expectedCases,
      `expected ${SHAPES.length} shapes squared; the loop above enumerated something else`);
    // 6 clauses per case: 2 ok-agreement directions, 2 partition-set comparisons, 1
    // no-overlap check, 1 union-vs-validateSchema comparison. Printed rather than only
    // asserted, so a run's real count reaches the PR body verbatim.
    console.log(`BLZ-407 oracle: ${cases} cases (${SHAPES.length} shapes squared), `
      + `${clauses} clauses checked so far this run`);
  });
});
